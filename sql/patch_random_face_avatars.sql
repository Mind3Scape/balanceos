-- ─────────────────────────────────────────────────────────────────────────────
-- РАЗОВЫЙ ПАТЧ: случайные ЛИЦА-ЭМОДЗИ всем, кто ни разу не менял аватарку
-- (David: «80% во Вселенной с одинаковым лицом — люди не понимают, что можно сменить»).
--
-- Что делает: каждому профилю БЕЗ выбранной аватарки (null / пустая / 'default'-сфера)
-- присваивает СЛУЧАЙНОЕ лицо из того же набора, что клиент раздаёт новичкам (v505).
-- Кастомные аватарки (emoji:…, m1…m18) НЕ трогаются.
-- random() вычисляется на каждую строку — лица получатся разные.
--
-- Повторный прогон безопасен: после присвоения avatar непустой — никого не найдёт.
-- Применять в Supabase SQL Editor. Клиент с v505 делает то же самое сам при входе
-- пользователя — этот патч нужен только чтобы ожили СРАЗУ ВСЕ, включая спящих.
-- ─────────────────────────────────────────────────────────────────────────────

update public.profiles
set avatar = 'emoji:' || (array[
  '😀','😃','😄','😁','😊','🙂','😉','😌','😎','🤓','🥳','🤩',
  '🥰','😇','🤠','😋','😜','🤪','🤗','🤭','🙃','😏','🧐','🫡'
])[floor(random() * 24)::int + 1]
where avatar is null or avatar = '' or avatar = 'default';

