-- Кастомная иконка ОБЩЕЙ ПРИВЫЧКИ круга (v828). НЕОБЯЗАТЕЛЬНЫЙ патч.
--
-- Что уже работает БЕЗ него:
--   • личные привычки и цели — уезжают в облако целым JSON-объектом, поле icon едет даром;
--   • эмблема круга — иконка прячется внутрь jsonb-колонки teams.goal (тем же приёмом,
--     каким там уже живёт accent), схему менять не нужно.
--
-- Что чинит патч: у ОБЩИХ привычек круга колонок фиксированный набор, jsonb там нет.
-- Пока колонки icon не существует, cloud.js спокойно откатывается на запись без неё
-- (слои «полное → базовое»), и выбранная иконка общей привычки просто не сохраняется —
-- показывается эмодзи. Ничего не падает и не теряется, кроме самой иконки.
--
-- Прогнать в Supabase → SQL Editor. Безопасно повторно.
-- ═══════════════════════════════════════════════════════════════════════════════════════

alter table public.team_habits add column if not exists icon text;

comment on column public.team_habits.icon is
  'id кастомной иконки из core/glyphs.jsx или NULL. Колонка emoji ВСЕГДА хранит настоящий эмодзи — его видят пуш-сервер и клиенты, которые иконки не рисуют.';
