-- patch_fix_self_referral.sql  (Этап 2 к фиксу v658)
--
-- Баг «сам себя пригласил»: в profiles.referred_by у человека лежал ЕГО ЖЕ id.
-- Из-за этого он видел СЕБЯ в друзьях и на орбите ДВАЖДЫ (invitedPeople и myInviter
-- оба возвращали его самого), а в детальном списке — не видел (там self фильтруется).
--
-- Причина: своя ссылка «поделиться привычкой» несёт хвост-реферал hb_<code>__<uid>;
-- открыв собственную ссылку без активной сессии, человек «приглашал сам себя».
--
-- Клиент v658 уже: (а) не создаёт таких строк (гард на обеих дверях входа),
-- (б) прячет self на чтении (фильтр + дедуп). Этот патч убирает УЖЕ записанные
-- кривые строки у всех, кого успело задеть. Идемпотентно и безопасно.

-- 1) Посмотреть ДО — сколько профилей заражено:
select count(*) as self_referrals_before
from public.profiles
where referred_by = id;

-- 2) Починка — обнулить «пригласивший = сам»:
update public.profiles
set referred_by = null
where referred_by = id;

-- 3) Проверка — должно стать 0:
select count(*) as self_referrals_after
from public.profiles
where referred_by = id;
