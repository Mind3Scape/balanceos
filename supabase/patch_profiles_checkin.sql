-- Часовой пояс пользователя (минуты от UTC; Москва = +180). Публикует приложение при
-- заходе. null = ещё не знаем → функция считает по Москве (+180), чтобы тест сработал.
alter table public.profiles add column if not exists tz_offset int;

-- Согласие на вечерний чек-ин. По умолчанию ВКЛ (мягкий, раз в неделю). Позже к нему
-- можно прикрутить тумблер в настройках.
alter table public.profiles add column if not exists checkin_on boolean not null default true;

-- Локальный день последнего чек-ина ('YYYY-MM-DD') — чтобы слать НЕ ЧАЩЕ раза в неделю.
alter table public.profiles add column if not exists checkin_last text;

