-- «Чем могу быть полезен» (offer) — короткое предложение помощи, которое видит твой круг
-- («Баланс окружения»). Воплощает «нести добро / быть полезным другим»: человек пишет, чем он
-- силён, и близкие видят это в списке людей + в подсказке ИИ («Аня может помочь: …»). Одна
-- текстовая колонка на профиле. Клиент работает и БЕЗ неё: saveOffer тихо роняет запись до ALTER
-- (не клинит очередь синка), profilesPublic/allPublic селектят offer «слоями» с graceful-fallback,
-- инпут всё равно помнит значение локально. Запусти ОДИН раз в Supabase → SQL Editor.
alter table public.profiles
  add column if not exists offer text;
