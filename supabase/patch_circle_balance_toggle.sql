-- Тумблер «Баланс круга» при настройке совместной цели (David: назвать именно «Баланс круга»,
-- НЕ «Аналитика»). Раздел «Баланс круга» на странице цели (кольцо-состояние круга + темп каждого)
-- по умолчанию ВКЛ у всех совместных целей; владелец может ВЫКЛЮЧИТЬ его в настройках цели.
-- Флаг живёт в одной булевой колонке команды. default true = прежнее поведение (показываем всем),
-- так что до применения ничего не ломается, а «выключено» появляется только когда владелец сам снял.
-- Клиент работает и БЕЗ этой колонки (cloud.js пишет/читает circle_balance_on «слоями» с graceful-
-- fallback; локальная копия команды всё равно помнит выбор) — но пока колонки нет, выбор «выключить»
-- не переживёт вход с нового устройства и не увидят другие участники. Запусти ОДИН раз в Supabase → SQL Editor.
alter table public.teams
  add column if not exists circle_balance_on boolean not null default true;
