-- ПРОБЛЕМА (аудит 2026-07-05, подтверждён живым curl): анонимный вход в проекте ВКЛючён
-- (Auth → anonymous_users = true), поэтому любой веб-гость через signInAnonymously() получает
-- роль `authenticated`. Единственная политика чтения — profiles_read = to authenticated
-- USING (true) — отдаёт ВСЕ строки и ВСЕ колонки, а колоночных грантов нет. Итог: кто угодно,
-- открыв приложение, может выгрузить tg_id (личный Telegram user-id) ВСЕЙ базы, а с ним имена,
-- реферальный граф, часовые пояса, дату последней активности.
--
-- РЕШЕНИЕ: оставляем построчный доступ (Вселенная показывает всех — это by design), но РЕЖЕМ
-- КОЛОНКИ. Отзываем select у роли authenticated и выдаём обратно ВСЁ, КРОМЕ tg_id. Приложение
-- tg_id у клиента нигде не читает (только сервер/edge-функции через service_role — на них грант
-- НЕ влияет, они продолжат слать пуши). referred_by остаётся — он нужен слою «Связи» во Вселенной.
--
-- БЕЗОПАСНОСТЬ ЭТОГО ПАТЧА: приложение читает из profiles только эти колонки — id, username, avatar,
-- pub_orbit, referred_by, ref_code (свой), created_at — все они в списке ниже. tg_id не читается
-- клиентом никогда. Запись (update) грантами SELECT не затрагивается — saveProfile/savePublicStats/
-- saveTz продолжат работать (они не делают .select() обратно).
-- ─────────────────────────────────────────────────────────────────────────────

revoke select on public.profiles from authenticated;

grant select
  (id, username, avatar, pub_orbit, referred_by, ref_code, tz_offset, checkin_on, checkin_last, created_at)
  on public.profiles to authenticated;

-- PostgREST кэширует схему — попросим перечитать (иначе новые гранты подхватятся не сразу).
notify pgrst, 'reload schema';

