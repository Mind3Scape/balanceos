--  Прогнать ОДИН раз: Supabase → SQL Editor → New query → вставь ВЕСЬ файл → RUN.
--  Безопасно: только переопределяет одну функцию is_member, данные не трогает.
-- ════════════════════════════════════════════════════════════════════════════
--
--  ПОЧЕМУ: is_member() считала членом ЛЮБУЮ строку team_members с твоим id —
--  включая строку role='pending' (ещё не принятую заявку). А чтение/запись чата и
--  список участников завязаны на is_member. Итог: человек, который только
--  «постучался» в ПРИВАТНЫЙ круг, уже мог читать и писать в чат и видеть ростер —
--  ДО одобрения. Одобрение было лишь визуальным, доступ не ограничивался.
--
--  ФИКС: is_member = членство ТОЛЬКО у принятых (role <> 'pending'). Заявитель
--  по-прежнему видит СВОЮ строку (в members_read есть user_id = auth.uid()), т.е.
--  «запрос отправлен» показывается, но чат/ростер закрыты до принятия.

create or replace function public.is_member(t uuid, u uuid)
returns boolean language sql security definer stable set search_path = public as $$
  select exists (
    select 1 from public.team_members m
    where m.team_id = t and m.user_id = u and m.role <> 'pending'
  );
$$;

