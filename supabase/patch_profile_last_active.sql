-- Свежесть «кто затих» (last_active) — метка последней активности человека (отметка привычки / вход).
-- Нужна, чтобы подсказки «Баланса окружения» были ЧЕСТНЫМИ: раньше «спад» считался по уровню/
-- активности, а не по «давно ли отмечался», и подсказка «поддержи X» иногда била мимо. С этой меткой
-- «затих» = реально давно не отмечался. Обновляется не чаще ~1/час (клиентский throttle), отдаётся в
-- profilesPublic. Клиент работает и БЕЗ колонки: touchActive тихо no-op до ALTER (прямая запись,
-- без очереди), profilesPublic селектит last_active «слоями»; при отсутствии данных подсказка НЕ
-- врёт «давно не заходил». Запусти ОДИН раз в Supabase → SQL Editor.
alter table public.profiles
  add column if not exists last_active timestamptz;
